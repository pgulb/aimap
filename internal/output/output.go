package output

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/pgulb/aimap/internal/symbol"
)

const generatedNotice = "<!-- GENERATED BY aimap. Do not edit manually. -->"

func kindLabel(k symbol.SymbolKind) string {
	switch k {
	case symbol.Function:
		return "function"
	case symbol.Method:
		return "method"
	case symbol.Struct:
		return "struct"
	case symbol.Interface:
		return "interface"
	case symbol.Type:
		return "type"
	case symbol.Variable:
		return "variable"
	case symbol.Constant:
		return "constant"
	case symbol.Class:
		return "class"
	default:
		return "symbol"
	}
}

// Render writes symbols to the specified output path as a markdown file.
// root is the absolute project root — used to relativize file paths in the output.
// The output file is fully generated; any existing content is replaced.
func Render(symbols []symbol.Symbol, root, outputPath string) error {
	var b strings.Builder
	b.WriteString(generatedNotice + "\n\n")
	b.WriteString("# Symbol Map\n\n")

	if len(symbols) == 0 {
		b.WriteString("No symbols found.\n")
		return os.WriteFile(outputPath, []byte(b.String()), 0644)
	}

	byFile := make(map[string][]symbol.Symbol)
	for _, s := range symbols {
		byFile[s.FilePath] = append(byFile[s.FilePath], s)
	}

	var filePaths []string
	for p := range byFile {
		filePaths = append(filePaths, p)
	}
	sort.Strings(filePaths)

	sections := []struct {
		label string
		files []string
	}{
		{"Go Files", nil},
		{"Python Files", nil},
		{"Other Files", nil},
	}

	for _, p := range filePaths {
		ext := strings.ToLower(filepath.Ext(p))
		switch ext {
		case ".go":
			sections[0].files = append(sections[0].files, p)
		case ".py":
			sections[1].files = append(sections[1].files, p)
		default:
			sections[2].files = append(sections[2].files, p)
		}
	}

	for _, sec := range sections {
		if len(sec.files) == 0 {
			continue
		}
		b.WriteString(fmt.Sprintf("### %s\n\n", sec.label))

		for _, p := range sec.files {
			syms := byFile[p]

			displayPath := relativize(root, p)
			b.WriteString(fmt.Sprintf("#### %s\n\n", displayPath))

			sort.Slice(syms, func(i, j int) bool {
				if syms[i].LineStart != syms[j].LineStart {
					return syms[i].LineStart < syms[j].LineStart
				}
				return syms[i].Name < syms[j].Name
			})

			for _, s := range syms {
				label := kindLabel(s.Kind)
				lineRange := formatLineRange(s.LineStart, s.LineEnd)
				name := s.Name

				if s.TypeParams != "" {
					name += s.TypeParams
				}

				if s.Parent != "" {
					name = fmt.Sprintf("%s.%s", s.Parent, name)
				}

				b.WriteString(fmt.Sprintf("- `%s` — %s %s", name, label, lineRange))

				if s.Comment != "" {
					commentLine := strings.SplitN(s.Comment, "\n", 2)[0]
					b.WriteString(fmt.Sprintf(" — %s", commentLine))
				}

				b.WriteString("\n")
			}
			b.WriteString("\n")
		}
	}

	return os.WriteFile(outputPath, []byte(b.String()), 0644)
}

func relativize(root, absPath string) string {
	rel, err := filepath.Rel(root, absPath)
	if err != nil {
		return filepath.Base(absPath)
	}
	return filepath.ToSlash(rel)
}

func formatLineRange(start, end int) string {
	if start == end {
		return fmt.Sprintf("(line %d)", start)
	}
	return fmt.Sprintf("(lines %d-%d)", start, end)
}
